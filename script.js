function showText(type) {
   if (type === 'Gaming') {
        document.getElementById('description').innerText = 'I love playing video games, especially Tactical and strategy games.';
   }
   if (type === 'Music') {
        document.getElementById('description').innerText = 'I enjoy listening to various genres of music, from pop to classical.';
   }
    if (type === 'RPL') {
        document.getElementById('description').innerText = 'I am passionate about programming and software development, particularly in the field of RPL.';
    }
}

    